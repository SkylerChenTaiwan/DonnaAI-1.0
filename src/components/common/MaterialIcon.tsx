/**
 * Material Icon 元件
 * Native 使用 @expo/vector-icons，Web 使用 CSS 字體
 */
export const MaterialIcon: React.FC<MaterialIconProps> = (props) => {
  const { name, size = 24, color = '#000', style } = props;
  const iconName = typeof name === 'string' ? name : String(name);
  
  // Web 平台使用 SVG 圖標
  if (Platform.OS === 'web') {
    // 獲取 SVG 路徑，如果沒有則使用預設的問號圖標
    const svgPath = materialSvgIcons[iconName] || materialSvgIcons['help'] || materialSvgIcons['error'];
    
    // 建立完整的 SVG 內容
    const svgContent = `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="${color}">${svgPath}</svg>`;
    
    // 轉換為 Data URI
    const dataUri = `data:image/svg+xml;utf8,${encodeURIComponent(svgContent)}`;
    
    // 使用 Image 元件顯示 SVG
    return (
      <Image
        source={{ uri: dataUri }}
        style={[
          {
            width: size,
            height: size,
          },
          style as any,
        ]}
      />
    );
  }
  
  // Native 平台使用 MaterialIcons
  return <MaterialIcons {...props} name={iconName as MaterialIconNames} />;
};

